"""Validation of the batched ML distance against AliSim truth and IQ-TREE's own pairwise ML distances.

Simulations are (re)generated by tests/alisim_sim.py into data/interim/tests/alisim/ (cached; ~5 min on 32 cores
the first time). Criteria (fixed before running):
  * unbiased: |mean(d_hat)/d - 1| < 3% for every d <= 2 (both lengths, both models); d = 3 reported only
  * agreement with IQ-TREE: median |d_ours/d_iq - 1| < 2% and 99th percentile < 2% for every configuration
  * no pair flagged saturated, all converged
"""
import json
import os
import shutil

import numpy as np
import pytest
import torch
from conftest import RESULTS

import alisim_sim
from strucevo.distances import AA_ORDER, load_model, ml_distance, pair_counts, simple_distances

pytestmark = pytest.mark.slow
DEV = "cuda" if torch.cuda.is_available() else "cpu"


@pytest.fixture(scope="module")
def table():
    if shutil.which(alisim_sim.IQTREE) is None:
        pytest.skip("iqtree3 not on PATH")
    dirs = alisim_sim.ensure(jobs=min(32, os.cpu_count() or 1))
    rows = []
    for wd in dirs:
        z = np.load(os.path.join(wd, "summary.npz"))
        model = str(z["model"])
        d = float(z["d_true"])
        C = pair_counts(list(z["A"]), list(z["B"]), AA_ORDER)
        r = ml_distance(C, load_model(model), alpha=alisim_sim.ALPHA, ncat=4, device=DEV)
        iq = z["iq"]
        rel = np.abs(r.d / iq - 1)
        simple = simple_distances(C)
        n = len(r.d)
        rows.append(dict(model=model, length=int(z["length"]), d=d, n=n,
                         mean_ours=float(r.d.mean()), mean_iq=float(iq.mean()),
                         rel_bias=float(r.d.mean() / d - 1),
                         mc_se_rel=float(r.d.std(ddof=1) / np.sqrt(n) / d),
                         sd_ours=float(r.d.std(ddof=1)), mean_se=float(np.nanmean(r.se)),
                         med_abs_rel_vs_iq=float(np.median(rel)), p99_abs_rel_vs_iq=float(np.quantile(rel, 0.99)),
                         max_abs_rel_vs_iq=float(rel.max()),
                         mean_p=float(np.mean(simple["p"])), mean_kimura=float(np.nanmean(simple["kimura"])),
                         frac_saturated=float(r.saturated.mean()), frac_converged=float(r.converged.mean())))
    json.dump(rows, open(os.path.join(RESULTS, "alisim_ml.json"), "w"), indent=1)
    return rows


def test_unbiased(table):
    bad = [r for r in table if r["d"] <= 2 and abs(r["rel_bias"]) >= 0.03]
    assert not bad, bad


def test_agrees_with_iqtree(table):
    bad = [r for r in table if r["med_abs_rel_vs_iq"] >= 0.02 or r["p99_abs_rel_vs_iq"] >= 0.02]
    assert not bad, bad


def test_flags_and_convergence(table):
    for r in table:
        assert r["frac_saturated"] == 0 and r["frac_converged"] == 1, r


def test_se_calibrated(table):
    for r in table:
        assert r["mean_se"] == pytest.approx(r["sd_ours"], rel=0.15), r
